// Action types + creators. Every action is a plain, JSON-serializable object
// so it can later be sent over the network for online multiplayer.

// Screen ids in play order. Step metadata (questions, owners, "answered") lives in ui/steps.js.
export const SCREENS = [
  'start', 'pickMission', 'size', 'science', 'power', 'comms', 'brains', 'orbit', 'rocket',
  'finalCheck', 'operations', 'results',
];

export const MAX_PLAYERS = 4;

export const T = {
  GO_TO_SCREEN: 'nav/goToScreen',
  SET_MODE: 'lobby/setMode',
  SET_DIFFICULTY: 'lobby/setDifficulty',
  ADD_PLAYER: 'lobby/addPlayer',
  REMOVE_PLAYER: 'lobby/removePlayer',
  RENAME_PLAYER: 'lobby/renamePlayer',
  ASSIGN_ROLE: 'lobby/assignRole',
  SET_ACTIVE_ROLE: 'roles/setActive',
  SELECT_SCENARIO: 'briefing/selectScenario',
  SELECT_COMPONENT: 'design/selectComponent',
  ADD_INSTRUMENT: 'design/addInstrument',
  REMOVE_INSTRUMENT: 'design/removeInstrument',
  SELECT_ORBIT: 'design/selectOrbit',
  SELECT_LAUNCHER: 'design/selectLauncher',
  SELECT_GROUND: 'design/selectGround',
  SELECT_POWER_PACK: 'design/selectPowerPack',
  SET_KIT: 'design/setKit',
  CAST_VOTE: 'review/castVote',
  RUN_SIMULATION: 'sim/run',
  RELAUNCH: 'sim/relaunch',
  CHOOSE_EVENT_OPTION: 'sim/chooseEventOption',
  LOAD_DESIGN: 'share/loadDesign',
  NEW_MISSION: 'debrief/newMission',
};

export const goToScreen = (screen) => ({ type: T.GO_TO_SCREEN, screen });
export const setMode = (mode) => ({ type: T.SET_MODE, mode });
export const setDifficulty = (difficulty) => ({ type: T.SET_DIFFICULTY, difficulty });
export const addPlayer = (name) => ({ type: T.ADD_PLAYER, name });
export const removePlayer = (index) => ({ type: T.REMOVE_PLAYER, index });
export const renamePlayer = (index, name) => ({ type: T.RENAME_PLAYER, index, name });
export const assignRole = (index, roleId) => ({ type: T.ASSIGN_ROLE, index, roleId });
export const setActiveRole = (roleId) => ({ type: T.SET_ACTIVE_ROLE, roleId });
export const selectScenario = (scenarioId) => ({ type: T.SELECT_SCENARIO, scenarioId });
export const selectComponent = (category, componentId) => ({ type: T.SELECT_COMPONENT, category, componentId });
export const addInstrument = (instrumentId) => ({ type: T.ADD_INSTRUMENT, instrumentId });
export const removeInstrument = (instrumentId) => ({ type: T.REMOVE_INSTRUMENT, instrumentId });
export const selectOrbit = (orbitId) => ({ type: T.SELECT_ORBIT, orbitId });
export const selectLauncher = (launcherId) => ({ type: T.SELECT_LAUNCHER, launcherId });
export const selectGround = (groundId) => ({ type: T.SELECT_GROUND, groundId });
export const selectPowerPack = (packId) => ({ type: T.SELECT_POWER_PACK, packId });
/** kit: 'standard' | 'upgraded' (Easy auto kits) | null (choose parts manually). */
export const setKit = (kit) => ({ type: T.SET_KIT, kit });
/** vote: 'go' | 'nogo' | null (clear). A No-Go must carry a reason id (data/roles.js NO_GO_REASONS). */
export const castVote = (roleId, vote, reason = null) => ({ type: T.CAST_VOTE, roleId, vote, reason });
/** seed must be generated by the caller (utils/random.newSeed) so the reducer stays pure. */
export const runSimulation = (seed) => ({ type: T.RUN_SIMULATION, seed });
/** After a launch failure: build a spare and fly again (extra cost, new seed from the caller). */
export const relaunch = (seed) => ({ type: T.RELAUNCH, seed });
/** Answer the simulation's pending event; the reducer replays the run with this decision. */
export const chooseEventOption = (choiceIndex) => ({ type: T.CHOOSE_EVENT_OPTION, choiceIndex });
export const newMission = () => ({ type: T.NEW_MISSION });
/** Load a shared design ({ scenarioId, difficulty, design } from utils/share.js). */
export const loadDesign = (shared) => ({ type: T.LOAD_DESIGN, shared });
